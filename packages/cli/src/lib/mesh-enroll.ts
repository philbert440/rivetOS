/**
 * Transport-agnostic mesh enroll/renew/sync core (plan D8).
 *
 * Unpack, layout, config-snippet merge, and cert-expiry math live here.
 * The SSH (or future HTTPS+token) hop is a single function in `commands/mesh.ts`
 * that returns stdout bytes; nothing in this module talks to the network.
 */

