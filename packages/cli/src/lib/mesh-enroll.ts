export const ENROLL_SNIPPET_MARKER = '# Generated by rivethub-hub enroll'
export const DEFAULT_HUB_CMD = 'rivethub-hub'
export const CERT_EXPIRY_WARN_DAYS = 30
export const DAY_MS = 24 * 60 * 60 * 1000

const TAR_BLOCK = 512

export type MeshHubErrorCode =
  'ssh-auth' | 'helper-missing' | 'malformed-tarball' | 'malformed-mesh' | 'usage'

export class MeshHubError extends Error {
  readonly code: MeshHubErrorCode
  constructor(code: MeshHubErrorCode, message: string) {
    super(message)
    this.name = 'MeshHubError'
    this.code = code
  }
}

